"""Train one digit classifier and compare it with a majority-class baseline."""

import argparse
import csv
import hashlib
import json
import platform
import warnings
from importlib.metadata import version
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # Save figures without requiring a desktop window.
import matplotlib.pyplot as plt
import numpy as np
from sklearn.datasets import load_digits
from sklearn.dummy import DummyClassifier
from sklearn.exceptions import ConvergenceWarning
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    ConfusionMatrixDisplay,
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
)
from sklearn.model_selection import train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

SEED = 42
TEST_SIZE = 0.20
LABELS = np.arange(10)


def split_indices(targets):
    """Preserve row identities and approximately preserve class proportions."""
    return train_test_split(
        np.arange(len(targets)),
        test_size=TEST_SIZE,
        random_state=SEED,
        stratify=targets,
    )


def score_predictions(expected, predicted):
    """Use all ten labels consistently, including absent predicted classes."""
    return {
        "accuracy": float(accuracy_score(expected, predicted)),
        "macro_f1": float(
            f1_score(expected, predicted, labels=LABELS, average="macro", zero_division=0)
        ),
        "correct": int(np.count_nonzero(np.asarray(expected) == predicted)),
        "total": len(expected),
        "confusion_matrix": confusion_matrix(expected, predicted, labels=LABELS).tolist(),
        "classification_report": classification_report(
            expected, predicted, labels=LABELS, output_dict=True, zero_division=0
        ),
    }


def plot_examples(images, targets, predictions, title, path):
    """Show a small, deterministic selection with a common pixel intensity scale."""
    columns = 5
    rows = max(1, (len(images) + columns - 1) // columns)
    fig, axes = plt.subplots(rows, columns, figsize=(10, 2.5 * rows), squeeze=False)
    for ax in axes.flat:
        ax.axis("off")
    if len(images) == 0:
        axes.flat[0].text(0.5, 0.5, "No misclassifications", ha="center")
    for i, (image, target) in enumerate(zip(images, targets)):
        ax = axes.flat[i]
        ax.imshow(image, cmap="gray_r", vmin=0, vmax=16, interpolation="nearest")
        label = f"True: {target}"
        if predictions is not None:
            label += f" | Predicted: {predictions[i]}"
        ax.set_title(label, fontsize=10)
    fig.suptitle(title)
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)


def write_summary(results, path):
    lines = [
        "# Evaluation results",
        "",
        "Generated by `python train_evaluate.py` from actual held-out predictions.",
        "",
        f"Split: {results['train_samples']} training / {results['test_samples']} test examples.",
        "Seed: 42. Stratified 80/20 split. Fixed settings; no hyperparameter search.",
        "",
        "| Model | Correct / test examples | Accuracy | Macro-F1 |",
        "| --- | ---: | ---: | ---: |",
    ]
    for name, scores in results["models"].items():
        lines.append(
            f"| {name} | {scores['correct']} / {scores['total']} | "
            f"{scores['accuracy']:.2%} | {scores['macro_f1']:.4f} |"
        )
    lines += [
        "",
        "Accuracy is the fraction of correct predictions. Macro-F1 averages each",
        "digit's F1 equally. The confusion matrix uses true labels as rows and",
        "predicted labels as columns. Undefined per-class scores are reported as zero.",
        "",
        "## Per-digit results for logistic regression",
        "",
        "| Digit | Precision | Recall | F1 | Test examples |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    report = results["models"]["logistic_regression"]["classification_report"]
    for label in LABELS:
        scores = report[str(label)]
        lines.append(
            f"| {label} | {scores['precision']:.4f} | {scores['recall']:.4f} | "
            f"{scores['f1-score']:.4f} | {int(scores['support'])} |"
        )
    lines += [
        "",
        "![Confusion matrix](confusion_matrix.png)",
        "",
        "![Misclassified test examples](misclassified_examples.png)",
        "",
        "The error plot shows up to the first 15 errors in the fixed test order,",
        "rather than handpicked successes. Exact predictions and source row indices",
        "are in `predictions.csv`; split membership is in `split_indices.json`.",
        "",
        "This evaluates a random split of the bundled digits dataset. It does not",
        "establish performance on new writers, photographed documents, or clinical data.",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run_experiment(output_dir):
    """Execute the complete experiment; repeated runs replace this directory's reports."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    digits = load_digits()
    X, y = digits.data, digits.target
    train, test = split_indices(y)

    # The scaler learns its mean/variance only when fitting on training rows.
    model = make_pipeline(
        StandardScaler(),
        LogisticRegression(C=1.0, solver="lbfgs", max_iter=1000),
    )
    baseline = DummyClassifier(strategy="most_frequent")
    with warnings.catch_warnings():
        warnings.simplefilter("error", ConvergenceWarning)
        model.fit(X[train], y[train])
    baseline.fit(X[train], y[train])
    predictions = model.predict(X[test])
    baseline_predictions = baseline.predict(X[test])

    fingerprint = hashlib.sha256(
        X.astype("<i2").tobytes() + y.astype("u1").tobytes()
    ).hexdigest()
    results = {
        "dataset": "sklearn.datasets.load_digits",
        "dataset_sha256": fingerprint,
        "dataset_samples": len(y),
        "features": X.shape[1],
        "train_samples": len(train),
        "test_samples": len(test),
        "settings": {
            "seed": SEED,
            "test_size": TEST_SIZE,
            "stratified": True,
            "scaler": "StandardScaler",
            "C": 1.0,
            "solver": "lbfgs",
            "max_iter": 1000,
        },
        "environment": {
            "python": platform.python_version(),
            **{name: version(name) for name in ("numpy", "scipy", "scikit-learn", "matplotlib")},
        },
        "models": {
            "majority_baseline": score_predictions(y[test], baseline_predictions),
            "logistic_regression": score_predictions(y[test], predictions),
        },
    }
    (output_dir / "metrics.json").write_text(
        json.dumps(results, indent=2, allow_nan=False) + "\n", encoding="utf-8"
    )
    (output_dir / "split_indices.json").write_text(
        json.dumps({"train": train.tolist(), "test": test.tolist()}, indent=2) + "\n",
        encoding="utf-8",
    )
    with (output_dir / "predictions.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["source_index", "true_label", "predicted_label", "baseline_label"])
        writer.writerows(zip(test, y[test], predictions, baseline_predictions))

    fig, ax = plt.subplots(figsize=(7, 6))
    ConfusionMatrixDisplay.from_predictions(
        y[test], predictions, labels=LABELS, display_labels=LABELS,
        cmap="Blues", colorbar=False, ax=ax,
    )
    ax.set_title("Logistic regression: held-out test predictions")
    fig.tight_layout()
    fig.savefig(output_dir / "confusion_matrix.png", dpi=160)
    plt.close(fig)
    examples = np.array([train[np.flatnonzero(y[train] == label)[0]] for label in LABELS])
    plot_examples(
        digits.images[examples], y[examples], None,
        "One training example per digit", output_dir / "training_examples.png",
    )
    errors = np.flatnonzero(predictions != y[test])[:15]
    plot_examples(
        digits.images[test[errors]], y[test[errors]], predictions[errors],
        "Misclassified test examples", output_dir / "misclassified_examples.png",
    )
    write_summary(results, output_dir / "summary.md")
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path("reports"))
    args = parser.parse_args()
    results = run_experiment(args.output_dir)
    for name, scores in results["models"].items():
        print(
            f"{name}: accuracy={scores['accuracy']:.4f}, "
            f"macro-F1={scores['macro_f1']:.4f}, "
            f"correct={scores['correct']}/{scores['total']}"
        )
    print(f"Reports saved to {args.output_dir}")


if __name__ == "__main__":
    main()
